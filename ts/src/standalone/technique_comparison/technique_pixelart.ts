export function renderPixelArt(): string {
  const pixelSize = 6; // 32 * 6 = 192px (fits in 200px viewBox)
  const offsetX = (200 - 32 * pixelSize) / 2; // center
  const offsetY = (200 - 32 * pixelSize) / 2;

  // Darker shade for left-side pixels (painter's algorithm)
  const darkFill = '#2965cc'; // darker version of FILL

  let rects = '';
  for (let y = 0; y < 32; y++) {
    for (let x = 0; x < 32; x++) {
      const val = SPRITE[y][x];
      if (val === 0) continue;
      const color = val === 3 ? darkFill : (val === 2 ? '#1e293b' : FILL);
      rects += `<rect x="${(offsetX + x * pixelSize).toFixed(1)}" y="${(offsetY + y * pixelSize).toFixed(1)}" width="${pixelSize}" height="${pixelSize}" fill="${color}"/>`;
    }
  }
  return rects;
}

